# Build the redacted evidence/summary.md from collector results.

function Protect-Cell {
    param([AllowNull()][string]$Text, $Context)
    $clean = Redact-Text -Text ([string]$Text) -Context $Context
    $clean = $clean.Replace('|', '/')
    $clean = $clean -replace "`r`n", ' '
    $clean = $clean -replace "`n", ' '
    return $clean
}

function Protect-Block {
    param([AllowNull()][string]$Text, $Context)
    return (Redact-Text -Text ([string]$Text) -Context $Context)
}

function Get-NewestRaw {
    param([string]$RepoRoot, [string]$Pattern)
    $dir = Join-Path $RepoRoot 'evidence\raw'
    if (-not (Test-Path -LiteralPath $dir)) { return $null }
    $files = @(Get-ChildItem -LiteralPath $dir -Filter $Pattern -File -ErrorAction SilentlyContinue | Sort-Object LastWriteTime -Descending)
    if ($files.Count -eq 0) { return $null }
    return $files[0].FullName
}

function Read-ResultJson {
    param([string]$Path)
    if ([string]::IsNullOrWhiteSpace($Path) -or -not (Test-Path -LiteralPath $Path)) { return $null }
    try {
        $text = [System.IO.File]::ReadAllText($Path)
        return ($text | ConvertFrom-Json)
    } catch {
        return $null
    }
}

function Write-EvidenceSummary {
    param(
        [Parameter(Mandatory = $true)][string]$RepoRoot,
        $Mission1,
        $Mission2,
        $Mission3
    )
    $context = Get-RedactionContext
    $generated = Get-IsoTimestamp
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('# Evidence summary') | Out-Null
    $lines.Add('') | Out-Null
    $lines.Add('Generated by `collect/run-all.ps1` on the computer where that command was run.') | Out-Null
    $lines.Add('Dynamic values are copied from that run and then redacted.') | Out-Null
    $lines.Add('User names, computer names, serial numbers, MAC addresses, and private IP addresses are omitted.') | Out-Null
    $lines.Add('This file is the one to send. Files in `evidence/raw/` can still contain a username inside a path.') | Out-Null
    $lines.Add('') | Out-Null
    $lines.Add('Generated (UTC): ' + $generated) | Out-Null
    $lines.Add('') | Out-Null

    $lines.Add('## Mission 1 — device profile') | Out-Null
    $lines.Add('') | Out-Null
    if ($null -eq $Mission1) {
        $lines.Add('Mission 1 was not run, and no earlier `m1-profile-*.json` was found.') | Out-Null
        $lines.Add('') | Out-Null
    } else {
        $lines.Add('Profile UTC: ' + (Protect-Cell -Text ([string](Get-Prop $Mission1 'generated_utc')) -Context $context)) | Out-Null
        $lines.Add('PowerShell: ' + (Protect-Cell -Text ([string](Get-Prop $Mission1 'powershell')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('| Area | Field | Status | Value | Source |') | Out-Null
        $lines.Add('| --- | --- | --- | --- | --- |') | Out-Null
        foreach ($field in @(ConvertTo-List (Get-Prop $Mission1 'fields'))) {
            $lines.Add(('| {0} | {1} | {2} | {3} | {4} |' -f `
                (Protect-Cell -Text ([string](Get-Prop $field 'area')) -Context $context), `
                (Protect-Cell -Text ([string](Get-Prop $field 'name')) -Context $context), `
                (Protect-Cell -Text ([string](Get-Prop $field 'status')) -Context $context), `
                (Protect-Cell -Text ([string](Get-Prop $field 'value')) -Context $context), `
                (Protect-Cell -Text ([string](Get-Prop $field 'source')) -Context $context))) | Out-Null
        }
        $lines.Add('') | Out-Null
        $candidates = [string](Get-Prop $Mission1 'feature_candidates')
        $lines.Add('### Observed facts available for your interpretation') | Out-Null
        $lines.Add('') | Out-Null
        if ([string]::IsNullOrWhiteSpace($candidates)) {
            $lines.Add('The collector did not derive an extra comparison. Choose one observed row above and write the implication yourself.') | Out-Null
        } else {
            $candidateBlock = Protect-Block -Text $candidates -Context $context
            $lines.Add($candidateBlock) | Out-Null
            $lines.Add('') | Out-Null
            $lines.Add('These lines restate collected numbers. They are not the interpretation. Write that in the report.') | Out-Null
        }
        $missionErrors = [string](Get-Prop $Mission1 'errors')
        if (-not [string]::IsNullOrWhiteSpace($missionErrors)) {
            $lines.Add('') | Out-Null
            $lines.Add('### Queries that failed') | Out-Null
            $lines.Add('') | Out-Null
            $lines.Add('```') | Out-Null
            $errorBlock = Protect-Block -Text $missionErrors -Context $context
            $lines.Add($errorBlock) | Out-Null
            $lines.Add('```') | Out-Null
        }
        $lines.Add('') | Out-Null
    }

    $lines.Add('## Mission 2 — browser task') | Out-Null
    $lines.Add('') | Out-Null
    if ($null -eq $Mission2) {
        $lines.Add('Mission 2 was not run, and no earlier `m2-session-*.json` was found.') | Out-Null
        $lines.Add('') | Out-Null
    } else {
        $lines.Add('Declared browser: ' + (Protect-Cell -Text ([string](Get-Prop $Mission2 'declared_browser')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('Declared pages: ' + (Protect-Cell -Text ([string](Get-Prop $Mission2 'declared_pages')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('Your note: ' + (Protect-Cell -Text ([string](Get-Prop $Mission2 'closing_note')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('Sample length requested (seconds): ' + (Protect-Cell -Text ([string](Get-Prop $Mission2 'sample_seconds')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('Counter resolution: ' + (Protect-Cell -Text ([string](Get-Prop $Mission2 'counter_note')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('CSV file: `' + (Protect-Cell -Text ([System.IO.Path]::GetFileName([string](Get-Prop $Mission2 'csv'))) -Context $context) + '`') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('### Stage statistics calculated from the CSV') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('Blank cells were ignored. A blank mean means that column was not exposed for the stage. These means are arithmetic means of the recorded samples, not a second measurement.') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('```') | Out-Null
        $stageStats = Protect-Block -Text ([string](Get-Prop $Mission2 'stage_stats')) -Context $context
        $lines.Add($stageStats) | Out-Null
        $lines.Add('```') | Out-Null
        $lines.Add('') | Out-Null
        $measurementNote = Protect-Block -Text ([string](Get-Prop $Mission2 'measurement_note')) -Context $context
        $lines.Add($measurementNote) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('### Screenshots') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('| File | Present when this summary was written |') | Out-Null
        $lines.Add('| --- | --- |') | Out-Null
        foreach ($relative in @(ConvertTo-List (([string](Get-Prop $Mission2 'expected_screenshots')) -split "`r?`n"))) {
            $name = [string]$relative
            if ([string]::IsNullOrWhiteSpace($name)) { continue }
            $full = Join-Path $RepoRoot ($name.Replace('/', '\'))
            $present = 'no'
            if (Test-Path -LiteralPath $full) { $present = 'yes' }
            $shotName = Protect-Cell -Text $name -Context $context
            $lines.Add(('| {0} | {1} |' -f $shotName, $present)) | Out-Null
        }
        $lines.Add('') | Out-Null
        $lines.Add('If a row says no, save that screenshot and run `collect\run-all.ps1` again, or edit this table yourself after you have saved the file. Do not mark yes for a file you have not saved.') | Out-Null
        $lines.Add('') | Out-Null
    }

    $lines.Add('## Mission 3 — virtual environment') | Out-Null
    $lines.Add('') | Out-Null
    if ($null -eq $Mission3) {
        $lines.Add('Mission 3 was not run, and no earlier `m3-result-*.json` was found.') | Out-Null
        $lines.Add('') | Out-Null
    } else {
        $lines.Add('Prediction confirmed before the run: ' + (Protect-Cell -Text ([string](Get-Prop $Mission3 'prediction_confirmed')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('Prediction confirmation UTC: ' + (Protect-Cell -Text ([string](Get-Prop $Mission3 'prediction_utc')) -Context $context)) | Out-Null
        $lines.Add('') | Out-Null
        $stopped = [string](Get-Prop $Mission3 'stopped')
        if (-not [string]::IsNullOrWhiteSpace($stopped)) {
            $lines.Add('Stopped: ' + (Protect-Cell -Text $stopped -Context $context)) | Out-Null
            $lines.Add('') | Out-Null
            $helpBlock = Protect-Block -Text ([string](Get-Prop $Mission3 'help')) -Context $context
            $lines.Add($helpBlock) | Out-Null
            $lines.Add('') | Out-Null
        }
        $lines.Add('| Item | Value |') | Out-Null
        $lines.Add('| --- | --- |') | Out-Null
        $mission3Rows = New-Object System.Collections.Generic.List[object]
        $mission3Rows.Add([pscustomobject]@{ Name = 'Python label'; Value = [string](Get-Prop $Mission3 'python_label') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Python version'; Value = [string](Get-Prop $Mission3 'python_version') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Python executable'; Value = [string](Get-Prop $Mission3 'python_executable') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 1 completed'; Value = [string](Get-Prop $Mission3 'run1_ok') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 1 stage'; Value = [string](Get-Prop $Mission3 'run1_stage') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 1 project exit code'; Value = [string](Get-Prop $Mission3 'run1_exit') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 1 .venv size (bytes)'; Value = [string](Get-Prop $Mission3 'run1_size_bytes') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 2 completed'; Value = [string](Get-Prop $Mission3 'run2_ok') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 2 project exit code'; Value = [string](Get-Prop $Mission3 'run2_exit') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Run 2 .venv size (bytes)'; Value = [string](Get-Prop $Mission3 'run2_size_bytes') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'pyvenv.cfg home'; Value = [string](Get-Prop $Mission3 'pyvenv_home') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'pyvenv.cfg include-system-site-packages'; Value = [string](Get-Prop $Mission3 'pyvenv_include_system') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'pyvenv.cfg version'; Value = [string](Get-Prop $Mission3 'pyvenv_version') }) | Out-Null
        $mission3Rows.Add([pscustomobject]@{ Name = 'Parent where.exe python unchanged after the child activation'; Value = [string](Get-Prop $Mission3 'parent_where_unchanged') }) | Out-Null
        foreach ($row in $mission3Rows) {
            $rowValue = Protect-Cell -Text $row.Value -Context $context
            $lines.Add(('| {0} | {1} |' -f $row.Name, $rowValue)) | Out-Null
        }
        $lines.Add('') | Out-Null
        $lines.Add('### Isolation') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('```') | Out-Null
        $isolationBlock = Protect-Block -Text ([string](Get-Prop $Mission3 'isolation_text')) -Context $context
        $lines.Add($isolationBlock) | Out-Null
        $lines.Add('```') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('### pip list comparison, system and run 1') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('```') | Out-Null
        $pipSystemBlock = Protect-Block -Text ([string](Get-Prop $Mission3 'pip_diff_system_text')) -Context $context
        $lines.Add($pipSystemBlock) | Out-Null
        $lines.Add('```') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('### Reproducibility') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('```') | Out-Null
        $reproBlock = Protect-Block -Text ([string](Get-Prop $Mission3 'reproducibility_text')) -Context $context
        $lines.Add($reproBlock) | Out-Null
        $lines.Add('```') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('### pip list comparison, run 1 and run 2') | Out-Null
        $lines.Add('') | Out-Null
        $lines.Add('```') | Out-Null
        $pipRunsBlock = Protect-Block -Text ([string](Get-Prop $Mission3 'pip_diff_runs_text')) -Context $context
        $lines.Add($pipRunsBlock) | Out-Null
        $lines.Add('```') | Out-Null
        $lines.Add('') | Out-Null
        $activation = [string](Get-Prop $Mission3 'activation_text')
        if (-not [string]::IsNullOrWhiteSpace($activation)) {
            $lines.Add('### Activation in a child process') | Out-Null
            $lines.Add('') | Out-Null
            $lines.Add('The parent PowerShell process did not dot-source `Activate.ps1`. A child process did, then exited.') | Out-Null
            $lines.Add('') | Out-Null
            $lines.Add('```') | Out-Null
            $activationBlock = Protect-Block -Text $activation -Context $context
            $lines.Add($activationBlock) | Out-Null
            $lines.Add('```') | Out-Null
            $lines.Add('') | Out-Null
        }
        $logName = [System.IO.Path]::GetFileName([string](Get-Prop $Mission3 'command_log'))
        if (-not [string]::IsNullOrWhiteSpace($logName)) {
            $lines.Add('Command log (local, may contain a username in a path): `' + (Protect-Cell -Text $logName -Context $context) + '`') | Out-Null
            $lines.Add('') | Out-Null
        }
    }

    $lines.Add('## What to send') | Out-Null
    $lines.Add('') | Out-Null
    $lines.Add('- The public repository URL.') | Out-Null
    $lines.Add('- The completed report (PDF or DOCX) built from `report/REPORT.md`.') | Out-Null
    $lines.Add('- This file, `evidence/summary.md`, after you have read the redaction check below.') | Out-Null
    $lines.Add('- The Task Manager screenshots listed in Mission 2.') | Out-Null
    $lines.Add('- A raw file from `evidence/raw/` only after you have read it and removed any username that remains in a path.') | Out-Null
    $lines.Add('') | Out-Null
    $lines.Add('## Redaction check') | Out-Null
    $lines.Add('') | Out-Null
    $body = $lines.ToArray() -join "`n"
    $userFound = 'no'
    $hostFound = 'no'
    $profileFound = 'no'
    $user = [string]$context.UserName
    $computer = [string]$context.Computer
    $profile = [string]$context.UserProfile
    if ($user.Length -ge 3 -and [regex]::IsMatch($body, '(?i)(?<=\\|/)' + [regex]::Escape($user) + '(?=\\|/|$)')) {
        $userFound = 'yes'
    }
    $commonHost = @('user', 'home', 'laptop', 'desktop', 'windows', 'python', 'system', 'admin', 'owner', 'computer', 'default', 'public')
    $checkHost = $computer.Length -ge 4
    foreach ($word in $commonHost) {
        if ($computer.Equals($word, [System.StringComparison]::OrdinalIgnoreCase)) {
            $checkHost = $false
        }
    }
    if ($checkHost -and [regex]::IsMatch($body, '(?i)\b' + [regex]::Escape($computer) + '\b')) {
        $hostFound = 'yes'
    }
    if (-not [string]::IsNullOrWhiteSpace($profile) -and $body.IndexOf($profile, [System.StringComparison]::OrdinalIgnoreCase) -ge 0) {
        $profileFound = 'yes'
    }
    $lines.Add('- User-profile path still present: ' + $profileFound) | Out-Null
    $lines.Add('- Username still present as a path segment: ' + $userFound) | Out-Null
    $lines.Add('- Computer name still present as a whole word: ' + $hostFound) | Out-Null
    $lines.Add('') | Out-Null
    if ($userFound -eq 'yes' -or $hostFound -eq 'yes' -or $profileFound -eq 'yes') {
        $lines.Add('Do not send this file until the remaining identifier is removed.') | Out-Null
    } else {
        $lines.Add('No user-profile path, username path segment, or computer-name word was found by this check. Read the file once yourself before you send it.') | Out-Null
    }
    $lines.Add('') | Out-Null

    $summaryPath = Join-Path $RepoRoot 'evidence\summary.md'
    Set-TextFile -Path $summaryPath -Content ($lines.ToArray() -join "`n")
    Write-Host ("Wrote {0}" -f $summaryPath)
    if ($userFound -eq 'yes' -or $hostFound -eq 'yes' -or $profileFound -eq 'yes') {
        Write-Host 'Redaction check found an identifier. Read evidence\summary.md before you send it.'
    }
    return $summaryPath
}
